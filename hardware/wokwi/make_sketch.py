#!/usr/bin/env python3
"""Build hardware/wokwi/sketch.ino from the real firmware.

Wokwi's web editor keeps every file in one flat folder, so the multi-file
firmware (MachineSafetyMonitor.ino + config.h + src/*.cpp) is joined into one
sketch here. The code itself is copied unchanged; only the #include lines that
point at our own files are dropped (everything is in one file now).

Run it again after changing the firmware:  python3 hardware/wokwi/make_sketch.py
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
FW = os.path.normpath(os.path.join(HERE, "..", "..", "firmware", "MachineSafetyMonitor"))

# Same order a compiler needs: settings, shared declarations, then every module.
ORDER = ["config.h", "src/app.h", "src/state.cpp", "src/strings.cpp", "src/util.cpp",
         "src/i2c_bus.cpp", "src/mpu6050.cpp", "src/ina219.cpp", "src/dht_sensor.cpp",
         "src/self_test.cpp", "src/sensors.cpp", "src/safety.cpp", "src/motor.cpp",
         "src/commands.cpp", "src/reports.cpp", "src/indicators.cpp", "src/lcd.cpp",
         "src/datalog.cpp", "MachineSafetyMonitor.ino"]
OWN_INCLUDE = re.compile(r'^\s*#include\s+"(\.\./config\.h|app\.h|src/app\.h)"\s*(//.*)?$')

out = ["// sketch.ino - Arduino Machine Safety Monitor, all firmware files joined for Wokwi.",
       "// GENERATED by hardware/wokwi/make_sketch.py - edit firmware/MachineSafetyMonitor instead.",
       "// Real project: https://github.com/DhairyaSanathara/Arduino-Machine-Safety-Monitor", ""]
for name in ORDER:
    out.append("// " + "=" * 74)
    out.append("// ===== " + name)
    out.append("// " + "=" * 74)
    for line in open(os.path.join(FW, name), encoding="utf-8").read().splitlines():
        if OWN_INCLUDE.match(line) or line.strip() == "#pragma once":
            continue
        if line.startswith("#define WOKWI_SIMULATION 0"):
            line = "#define WOKWI_SIMULATION 1   // set by make_sketch.py: this copy runs in Wokwi"
        out.append(line)
    out.append("")
open(os.path.join(HERE, "sketch.ino"), "w", encoding="utf-8").write("\n".join(out) + "\n")
print("wrote sketch.ino, %d lines" % len(out))
